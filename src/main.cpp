void center(String text, int y)
{
  int16_t x2, y2;
  uint16_t width, height;

  tft.getTextBounds(text, 0, y, &x2, &y2, &width, &height);

  int x = (tft.width() - width) / 2;

  tft.setCursor(x, y);
  tft.print(text);
}