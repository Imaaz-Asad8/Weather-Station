void loop()
{

  if (counter > 2)
  {
    counter = 0;
  }

  if (millis() - sht_millis > 300000 || sht_millis == 0)
  {

    getInternalTemp();
    sht_time = getTime();
    sht_millis = millis();
    update = true;
  }

  if (millis() - hourly_api_millis > 900000 || hourly_api_millis == 0)
  {

    if (getHourlyWeather())
    {
      api_time = getTime();
      update = true;
    }
    hourly_api_millis = millis();
  }

  if (millis() - daily_api_millis > 3600000 || daily_api_millis == 0)
  {
    Serial.println("Called weather");

    if (getDailyWeather())
    {
      api_time = getTime();
      update = true;
    }
    Serial.println("Left weather.");
    daily_api_millis = millis();
  }

  button_state = digitalRead(button_pin);

  if (button_state == LOW && previous_state == HIGH)
  {
    if (millis() - bounce_millis > 200)
    {
      bounce_millis = millis();
      counter++;
    }
  }

  previous_state = button_state;

  if (last_screen != counter || update)
  {
    if (counter == 0)
    {
      screen1();
    }
    else if (counter == 1)
    {
      screen2();
    }
    else if (counter == 2)
    {
      screen3();
    }
    last_screen = counter;
    update = false;
  }
}
String getTime()
{

  String noon;
  timeClient.update();
  int hours = timeClient.getHours();

  if (hours == 0)
  {
    noon = "AM";
    hours = 12;
  }
  else if (hours < 12)
  {
    noon = "AM";
  }
  else if (hours == 12)
  {
    noon = "PM";
  }
  else
  {
    noon = "PM";
    hours -= 12;
  }

  int minutes = timeClient.getMinutes();
  String string_minutes;

  if (minutes < 10)
  {
    string_minutes = "0" + String(minutes);
  }
  else
  {
    string_minutes = String(minutes);
  }

  return String(hours) + ":" + string_minutes + " " + noon;
}

